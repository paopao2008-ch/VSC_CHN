/*------------------------------------------------------------------------------
 * 按 Unicode 码点找汉字字模（找不到返回 NULL）
 *----------------------------------------------------------------------------*/
const uint8_t *CN_Font_Find(uint32_t Code)
{
    uint16_t i;
    for (i = 0u; i < CN_FontCount; i++)
    {
        if (CN_FontTable[i].Code == Code) { return CN_FontTable[i].Data; }
        if (CN_FontTable[i].Code > Code)  { return (const uint8_t *)0; }  /* 已升序，可提前退出 */
    }
    return (const uint8_t *)0;
}

/*------------------------------------------------------------------------------
 * 取半角 ASCII 8x16 字模（不在 0x20~0x7E 范围内返回空格）
 *----------------------------------------------------------------------------*/
const uint8_t *CN_Font_Ascii(uint8_t Ch)
{
    if ((Ch < 0x20u) || (Ch > 0x7Eu)) { Ch = 0x20u; }
    return &Font8x16[Ch - 0x20u][0];
}

/*------------------------------------------------------------------------------
 * UTF-8 解码：取一个字符
 *   返回该字符占用的字节数（1~4），码点写入 *Code；遇到非法序列按 1 字节处理
 *   - 0x00~0x7F : 1 字节 ASCII
 *   - 0x80~0x7FF: 2 字节
 *   - 0x800~FFFF: 3 字节（CJK 基本区都落在这里）
 *----------------------------------------------------------------------------*/
uint8_t CN_Utf8Next(const char *S, uint32_t *Code)
{
    const uint8_t *p = (const uint8_t *)S;
    uint8_t  b0 = p[0];
    uint8_t  n;
    uint32_t c;

    if (b0 < 0x80u)                       { *Code = (uint32_t)b0;              return 1u; }
    if ((b0 & 0xE0u) == 0xC0u)            { n = 2u; c = (uint32_t)(b0 & 0x1Fu); }
    else if ((b0 & 0xF0u) == 0xE0u)       { n = 3u; c = (uint32_t)(b0 & 0x0Fu); }
    else if ((b0 & 0xF8u) == 0xF0u)       { n = 4u; c = (uint32_t)(b0 & 0x07u); }
    else                                  { *Code = (uint32_t)b0;              return 1u; }

    {
        uint8_t i;
        for (i = 1u; i < n; i++)
        {
            if ((p[i] & 0xC0u) != 0x80u)  /* 续字节不合法，退化成单字节 */
            {
                *Code = (uint32_t)b0;
                return 1u;
            }
            c = (uint32_t)((c << 6) | (uint32_t)(p[i] & 0x3Fu));
        }
    }
    *Code = c;
    return n;
}
